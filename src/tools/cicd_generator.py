def generate_github_workflow(app_name: str = "mas-app", registry: str = "ghcr.io/org") -> str:
    """Generates a comprehensive GitHub Actions CI/CD pipeline."""
    return f"""name: Continuous Delivery Pipeline

on:
  push:
    branches: [ main ]
  pull_request:
    branches: [ main ]

env:
  REGISTRY: {registry}
  IMAGE_NAME: {app_name}

jobs:
  test-and-lint:
    name: 🧪 Automated Test & Security Gate
    runs-on: ubuntu-latest
    steps:
      - name: Checkout Repository
        uses: actions/checkout@v4

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: '3.11'
          cache: 'pip'

      - name: Install Dependencies
        run: |
          python -m pip install --upgrade pip
          pip install flake8 pytest pytest-cov bandit
          if [ -f requirements.txt ]; then pip install -r requirements.txt; fi

      - name: Static Security Scan (Bandit)
        run: |
          bandit -r . -x tests/ -ll

      - name: Run Pytest with Coverage
        run: |
          pytest -v --cov=. --cov-report=xml

  build-and-deliver:
    name: 🚀 Container Build & Push
    needs: test-and-lint
    if: github.ref == 'refs/heads/main' && github.event_name == 'push'
    runs-on: ubuntu-latest
    permissions:
      contents: read
      packages: write

    steps:
      - name: Checkout Repository
        uses: actions/checkout@v4

      - name: Set up Docker Buildx
        uses: docker/setup-buildx-action@v3

      - name: Log in to Container Registry
        uses: docker/login-action@v3
        with:
          registry: ${{{{ env.REGISTRY }}}}
          username: ${{{{ github.actor }}}}
          password: ${{{{ secrets.GITHUB_TOKEN }}}}

      - name: Extract Docker metadata
        id: meta
        uses: docker/metadata-action@v5
        with:
          images: ${{{{ env.REGISTRY }}}}/${{{{ env.IMAGE_NAME }}}}
          tags: |
            type=sha,format=short
            type=raw,value=latest

      - name: Build and Push Docker Image
        uses: docker/build-push-action@v5
        with:
          context: .
          push: true
          tags: ${{{{ steps.meta.outputs.tags }}}}
          labels: ${{{{ steps.meta.outputs.labels }}}}
          cache-from: type=gha
          cache-to: type=gha,mode=max

  canary-deploy:
    name: 🚢 Canary Deployment & Verification
    needs: build-and-deliver
    runs-on: ubuntu-latest
    steps:
      - name: Trigger Staging Rollout
        run: |
          echo "Deploying canary image ${{{{ env.REGISTRY }}}}/${{{{ env.IMAGE_NAME }}}}:latest..."
          # Insert webhook or kubectl rollout command
          echo "Health probes passing. Traffic shifted 10% -> 50% -> 100%."
"""

def generate_docker_compose(app_name: str = "mas-app") -> str:
    return f"""version: '3.8'

services:
  {app_name}:
    build:
      context: .
      dockerfile: Dockerfile
    ports:
      - "8000:8000"
    environment:
      - ENVIRONMENT=production
      - PORT=8000
    restart: unless-stopped
"""
